# Read the raw recipe pre-start hooks from one resolved configuration.
def recipe_pre_start(configuration: Mapping[str, Any], service: str) -> list[dict[str, Any]]:
    # Require the services table.
    services: Mapping[str, Any] = _mapping(configuration.get("services"), "services")

    # Require the selected service mapping.
    selected: Mapping[str, Any] = _mapping(services.get(service), f"services.{service}")

    # Read the recipe startup hooks.
    value: Any = selected.get("pre_start")

    # If the recipe does not declare startup hooks, retain an empty sequence.
    if value is None:
        # Return no hooks.
        return []

    # If the hook sequence is invalid, report its configuration location.
    if not isinstance(value, list):
        # Throw.
        raise RecipeUnresolved(f"services.{service}.pre_start", "Must be an array of startup hooks.")

    # Preserve every recipe hook field without normalizing or dropping its settings.
    hooks: list[dict[str, Any]] = []
    for index, entry in enumerate(value):
        # Require a hook mapping.
        if not isinstance(entry, Mapping):
            # Throw.
            raise RecipeUnresolved(f"services.{service}.pre_start[{index}]", "Must be a mapping.")

        # Record the hook unchanged.
        hooks.append(dict(entry))

    # Return the ordered recipe hooks.
    return hooks


# Require a mapping value at one resolved-configuration field.
def _mapping(value: object, field: str) -> Mapping[str, Any]:
    # If the value is not a mapping.
    if not isinstance(value, Mapping):
        # Throw.
        raise RecipeUnresolved(field, "Must be a mapping.")

    # Return the mapping.
    return value


# Normalize labels from the resolved mapping or array form.
def _labels(value: object, field: str) -> dict[str, str]:
    # If labels are absent, return an empty mapping.
    if value is None:
        # Return no labels.
        return {}

    # Delegate the shared mapping and array rules.
    return _pairs(value, field)


# Normalize a name-to-value mapping or array.
def _pairs(value: object, field: str) -> dict[str, str]:
    # Normalize the mapping form.
    if isinstance(value, Mapping):
        # Prepare the normalized pairs.
        pairs: dict[str, str] = {}

        # For each pair.
        for name, item in value.items():
            # If the name or value is invalid.
            if not isinstance(name, str) or not name or not isinstance(item, str):
                # Throw.
                raise RecipeUnresolved(field, "Must contain string names and values.")

            # Record the pair.
            pairs[name] = item

        # Return the pairs.
        return pairs

    # Normalize the array form.
    if isinstance(value, list):
        # Prepare the normalized pairs.
        pairs = {}

        # For each name=value entry.
        for index, item in enumerate(value):
            # If the entry is not a string pair.
            if not isinstance(item, str) or "=" not in item:
                # Throw.
                raise RecipeUnresolved(f"{field}[{index}]", "Must use the `name=value` form.")

            # Split the name and value.
            name, item_value = item.split("=", 1)

            # If the name is blank.
            if not name:
                # Throw.
                raise RecipeUnresolved(f"{field}[{index}]", "Must use a nonblank name.")

            # Record the pair.
            pairs[name] = item_value

        # Return the pairs.
        return pairs

    # Throw.
    raise RecipeUnresolved(field, "Must be a mapping or an array of `name=value` strings.")


# Resolve one local path against the catalogue root without requiring it to exist.
def _local_path(value: object, catalogue_root: Path, field: str) -> Path:
    # Require a nonblank string path.
    if not isinstance(value, str) or not value:
        # Throw.
        raise RecipeUnresolved(field, "Must be a nonblank local path.")

    # Reject remote build and bind sources.
    if "://" in value or value.startswith("git@"):
        # Throw.
        raise RecipeUnresolved(field, "Must be a local path inside the catalogue directory.")

    # Expand the user and resolve relative paths against the catalogue root.
    path: Path = Path(value).expanduser()
    if not path.is_absolute():
        # Anchor the path at the catalogue root.
        path = catalogue_root / path

    # Return the absolute path without requiring it to exist.
    return path.resolve(strict = False)


# Resolve a Compose volume key to its physical volume name.
def _physical_volume_name(source: object, definitions: object, field: str) -> str:
    # Require a named volume key.
    if not isinstance(source, str) or not source:
        # Throw.
        raise RecipeUnresolved(field, "Must be a nonblank string.")

    # Normalize the top-level volume definitions.
    volume_definitions: Mapping[str, Any] = {} if definitions is None else _mapping(definitions, "volumes")

    # Read the definition when the key is declared.
    definition: Any = volume_definitions.get(source)
    if definition is None:
        # Use the Compose key as the physical name.
        return source

    # Require the definition mapping.
    definition = _mapping(definition, f"volumes.{source}")

    # Read the physical name or fall back to the key.
    name: Any = definition.get("name", source)
    if not isinstance(name, str) or not name:
        # Throw.
        raise RecipeUnresolved(field, "Must resolve to a nonblank physical volume name.")

    # Return the physical name.
    return name


# Project the effective service mounts.
def _mounts(value: object, definitions: object, catalogue_root: Path, field: str) -> tuple[MountSpec, ...]:
    # If mounts are absent, use an empty sequence.
    if value is None:
        # Return no mounts.
        return ()

    # Require an array of mounts.
    if not isinstance(value, list):
        # Throw.
        raise RecipeUnresolved(field, "Must be an array of mounts.")

    # Prepare the projected mounts.
    mounts: list[MountSpec] = []

    # For each resolved mount.
    for index, entry in enumerate(value):
        # Require a mapping mount.
        mount: Mapping[str, Any] = _mapping(entry, f"{field}[{index}]")

        # Require the mount type and target.
        mount_type: Any = mount.get("type")
        target: Any = mount.get("target")
        if not isinstance(target, str) or not target:
            # Throw.
            raise RecipeUnresolved(f"{field}[{index}].target", "Must be a nonblank string.")

        # Require a Boolean read-only flag.
        read_only: bool = mount.get("read_only") is True

        # Project a bind mount as an absolute host path.
        if mount_type == "bind":
            # Resolve the local bind source.
            source: Path = _local_path(mount.get("source"), catalogue_root, f"{field}[{index}].source")

            # Record the bind mount.
            mounts.append(MountSpec(kind = "bind", source = source, target = target, read_only = read_only))
            continue

        # Project a named volume as its physical name.
        if mount_type == "volume":
            # Resolve the physical volume name.
            name: str = _physical_volume_name(mount.get("source"), definitions, f"{field}[{index}].source")

            # Record the volume mount.
            mounts.append(MountSpec(kind = "volume", source = name, target = target, read_only = read_only))
            continue

        # Reject every unsupported mount form.
        raise RecipeUnresolved(f"{field}[{index}].type", "Only bind and named volume mounts are supported.")

    # Return the projected mounts.
    return tuple(mounts)


# Project the effective service networks.
def _networks(definitions: object, service_networks: object, field: str, *, skip: bool) -> tuple[NetworkFacts, ...]:
    # If the service selects a network mode, Compose does not use named networks.
    if skip:
        # Return no network attachments.
        return ()

    # Use the default network when the service names none.
    if service_networks is None:
        # Select the default network.
        used: tuple[object, ...] = ("default",)

    # Read names from the mapping or array form.
    elif isinstance(service_networks, (Mapping, list)):
        # Select the declared names.
        used = tuple(service_networks)

    # Otherwise, throw.
    else:
        # Throw.
        raise RecipeUnresolved(field, "Must be an array or mapping of network names.")

    # Use the default network when the service names an empty set.
    if not used:
        # Select the default network.
        used = ("default",)

    # Require the top-level network table.
    networks: Mapping[str, Any] = _mapping(definitions, "networks")

    # Prepare the projected networks.
    resolved: list[NetworkFacts] = []

    # For each used network.
    for name in used:
        # Require a nonblank name.
        if not isinstance(name, str) or not name:
            # Throw.
            raise RecipeUnresolved(field, "Must contain nonblank network names.")

        # If the network is not defined.
        if name not in networks:
            # Throw.
            raise RecipeUnresolved(field, f"Network `{name}` is not defined in the resolved configuration.")

        # Require the network definition.
        network: Mapping[str, Any] = _mapping(networks[name], f"networks.{name}")

        # Project the effective name and labels.
        resolved.append(NetworkFacts(name = name, labels = _labels(network.get("labels"), f"networks.{name}.labels")))

    # Return the projected networks.
    return tuple(resolved)


# Project environment files as absolute local paths.
def _environment_files(value: object, catalogue_root: Path, field: str) -> tuple[Path, ...]:
    # If no environment files are declared, return an empty sequence.
    if value is None:
        # Return no files.
        return ()

    # Accept a single entry or an array of entries.
    entries: list[object] = value if isinstance(value, list) else [value]

    # Prepare the resolved files.
    files: list[Path] = []

    # For each declared entry.
    for index, entry in enumerate(entries):
        # If the entry is a path string.
        if isinstance(entry, str):
            # Use the string as the path value.
            path_value: object = entry

        # If the entry is a mapping.
        elif isinstance(entry, Mapping):
            # Read the path.
            path_value = entry.get("path")

        # Otherwise, throw.
        else:
            # Throw.
            raise RecipeUnresolved(f"{field}[{index}]", "Must be a path string or mapping.")

        # Resolve the local environment file path.
        files.append(_local_path(path_value, catalogue_root, f"{field}[{index}]"))

    # Return the resolved files.
    return tuple(files)


# Validate declared secret forms and return their names in declaration order.
def _declared_secrets(value: object) -> tuple[str, ...]:
    # If no secrets are declared, return an empty sequence.
    if value is None:
        # Return no declarations.
        return ()

    # Require a top-level secrets table.
    declarations: Mapping[str, Any] = _mapping(value, "secrets")

    # Prepare the declared names.
    names: list[str] = []

    # For each declaration.
    for name, entry in declarations.items():
        # Require a nonblank secret name.
        if not isinstance(name, str) or not name:
            # Throw.
            raise RecipeUnresolved("secrets", "Must contain nonblank secret names.")

        # Require the declaration mapping.
        declaration: Mapping[str, Any] = _mapping(entry, f"secrets.{name}")

        # Read the supported declaration forms.
        file: Any = declaration.get("file")
        environment: Any = declaration.get("environment")
        external: Any = declaration.get("external", False)

        # If the file declaration is invalid.
        if file is not None and (not isinstance(file, str) or not file):
            # Throw.
            raise RecipeUnresolved(f"secrets.{name}.file", "Must be a nonblank path.")

        # If the environment declaration is invalid.
        if environment is not None and (not isinstance(environment, str) or not environment):
            # Throw.
            raise RecipeUnresolved(f"secrets.{name}.environment", "Must be a nonblank environment variable name.")

        # If no supported secret source is declared.
        if file is None and environment is None and not external:
            # Throw.
            raise RecipeUnresolved(f"secrets.{name}", "Must declare `file`, `environment`, or `external`.")

        # Record the declaration order.
        names.append(name)

    # Return the declared names.
    return tuple(names)


# Project the service secret references.
def _service_secrets(value: object, field: str) -> tuple[str, ...]:
    # If no secret references are declared, return an empty sequence.
    if value is None:
        # Return no references.
        return ()

    # Require an array of references.
    if not isinstance(value, list):
        # Throw.
        raise RecipeUnresolved(field, "Must be an array of secret references.")

    # Prepare the referenced names.
    names: list[str] = []

    # For each reference.
    for index, entry in enumerate(value):
        # If the entry is a secret name.
        if isinstance(entry, str):
            # Use the name directly.
            source: object = entry

        # If the entry is a mapping.
        elif isinstance(entry, Mapping):
            # Read its source.
            source = entry.get("source")

        # Otherwise, throw.
        else:
            # Throw.
            raise RecipeUnresolved(f"{field}[{index}]", "Must be a secret name or mapping.")

        # Require a nonblank declared name.
        if not isinstance(source, str) or not source:
            # Throw.
            raise RecipeUnresolved(f"{field}[{index}]", "Must name a declared secret.")

        # Record the reference.
        names.append(source)

    # Return the referenced names in resolved order.
    return tuple(names)


