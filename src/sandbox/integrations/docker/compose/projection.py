# Imports.
import shlex
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

# Import domain values.
from sandbox.domain import (
    Initialization,
    MountSpec,
    RecipeDefinition,
    SandboxPlan,
    SandboxSpec,
)

# Import the typed input errors.
from sandbox.errors.recipes import RecipeUnresolved


# Record one effective lifecycle hook from the resolved Compose model.
@dataclass(frozen = True, slots = True)
class HookFacts:
    # Record the optional explicit user.
    user: str | int | None

    # Record whether the hook requests privileged access.
    privileged: bool

    # Record the effective hook labels.
    labels: Mapping[str, str]

    # Record the optional entrypoint arguments.
    entrypoint: tuple[str, ...] | None

    # Record the optional command arguments.
    command: tuple[str, ...] | None

    # Record the added capabilities.
    cap_add: tuple[str, ...]

    # Record the dropped capabilities.
    cap_drop: tuple[str, ...]

    # Record the hook mounts.
    mounts: tuple[MountSpec, ...]

    # Record whether the hook is generated by sandbox or declared by the recipe.
    origin: str


# Record the effective hook sequences in declaration order.
@dataclass(frozen = True, slots = True)
class HooksFacts:
    # Record the pre-start hooks.
    pre_start: tuple[HookFacts, ...]

    # Record the post-start hooks.
    post_start: tuple[HookFacts, ...]

    # Record the pre-stop hooks.
    pre_stop: tuple[HookFacts, ...]


# Record one effective network attachment and its labels.
@dataclass(frozen = True, slots = True)
class NetworkFacts:
    # Record the network name.
    name: str

    # Record the network labels.
    labels: Mapping[str, str]


# Record every effective fact used to verify the realized override.
@dataclass(frozen = True, slots = True)
class ServiceFacts:
    # Record the selected service name.
    service: str

    # Record the effective image reference.
    image: str

    # Record the effective platform.
    platform: str | None

    # Record the effective service user.
    user: str | int | None

    # Record the effective working directory.
    working_directory: str | None

    # Record whether privileged mode is effective.
    privileged: bool

    # Record whether host networking is effective.
    host_network: bool

    # Record the effective service labels.
    labels: Mapping[str, str]

    # Record the effective mounts.
    mounts: tuple[MountSpec, ...]

    # Record the effective network attachments.
    networks: tuple[NetworkFacts, ...]

    # Record the effective environment files.
    environment_files: tuple[Path, ...]

    # Record every declared top-level secret name.
    declared_secrets: tuple[str, ...]

    # Record the service secret references.
    secrets: tuple[str, ...]

    # Record the resolved build mapping when the service declares one.
    build: Mapping[str, Any] | None

    # Record the effective lifecycle hook sequences.
    hooks: HooksFacts


# Record the neutral requirements and private verification facts for one service.
@dataclass(frozen = True, slots = True)
class Projection:
    # Record the neutral sandbox spec.
    spec: SandboxSpec

    # Record the private effective facts.
    facts: ServiceFacts


# Require a mapping value at one resolved-configuration field.
def _mapping(value: object, field: str) -> Mapping[str, Any]:
    # If the value is not a mapping.
    if not isinstance(value, Mapping):
        # Throw.
        raise RecipeUnresolved(field, "Must be a mapping.")

    # Return the mapping.
    return value
